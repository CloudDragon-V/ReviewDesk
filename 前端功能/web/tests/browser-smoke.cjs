/* Run against an isolated Workbench server, never a user's active knowledge database. */
const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'C:/Users/hq/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')

async function main() {
  const base = process.env.REVIEWDESK_TEST_URL || 'http://127.0.0.1:8876'
  const output = process.env.REVIEWDESK_TEST_OUTPUT || path.resolve(__dirname, '../../../其它/verification')
  fs.mkdirSync(output, { recursive: true })
  const browser = await chromium.launch({ headless: true, channel: process.env.PLAYWRIGHT_CHANNEL || 'msedge' })
  const page = await browser.newPage({ viewport: { width: 1500, height: 1100 }, deviceScaleFactor: 1, acceptDownloads: true })
  const errors = [], actions = [], failures = []
  let paidRequests = 0
  page.on('request', request => {
    if (request.url().endsWith('/api/manual') && request.method() === 'POST' && request.postDataJSON()?.use_ai) paidRequests++
  })
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  page.on('response', response => { if (response.status() >= 400) failures.push({ status: response.status(), url: response.url().split('?')[0] }) })
  async function shot(name) { await page.screenshot({ path: path.join(output, `v02-ui-${name}.png`), fullPage: !['manual', 'ai-preview-only'].includes(name) }) }
  async function chooseTab(name) { await page.getByRole('navigation', { name: '代码阅读功能' }).getByRole('button', { name, exact: false }).click() }
  try {
    // Explicit UI-only fixture for an isolated server with credentials disabled.
    // The actual preview still comes from the backend; no key is saved or sent.
    if (process.env.REVIEWDESK_TEST_KEY_FIXTURE === '1') {
      await page.route('**/api/bootstrap', async route => {
        const response = await route.fetch()
        const bootstrap = await response.json()
        return route.fulfill({ response, json: { ...bootstrap, has_key: true } })
      })
      actions.push('explicit bootstrap has_key UI fixture; no credential stored or read by this fixture')
    }
    await page.goto(base, { waitUntil: 'networkidle' })
    await page.getByText('本地服务已连接', { exact: false }).waitFor()
    await shot('welcome')
    await page.getByRole('button', { name: '打开示例项目', exact: false }).click()
    await page.locator('.sidebar-action:has-text("打开示例项目"):not(:disabled)').waitFor({ timeout: 30000 })
    await page.getByRole('navigation', { name: '代码阅读功能' }).waitFor({ timeout: 30000 })
    await page.getByRole('heading', { name: '先找到入口，再沿着调用读下去。' }).waitFor()
    actions.push('real demo import and overview')
    await shot('overview')
    await chooseTab('函数调用')
    await page.locator('.graph-node').first().click()
    await page.locator('.compact-details').waitFor()
    assert.ok(await page.locator('.code-line.selected').count() > 0)
    actions.push('click graph node and locate source')
    await page.getByRole('button', { name: '放大', exact: true }).click()
    await page.getByRole('button', { name: '缩小', exact: true }).click()
    await shot('calls')
    await chooseTab('模块与函数')
    await page.getByRole('searchbox', { name: '搜索模块与函数' }).fill('main')
    assert.ok(await page.locator('.symbol-picker button').count() > 0)
    await page.locator('.symbol-picker button').first().click()
    await page.locator('.symbol-details').waitFor()
    actions.push('symbol search, input steps return details')
    await shot('symbols')
    await chooseTab('变量变化')
    await page.locator('.variable-card').first().waitFor()
    assert.ok(await page.locator('.variable-card').count() > 0)
    await page.locator('.variable-timeline .line-link').first().click()
    assert.ok(await page.locator('.code-line.selected').count() > 0)
    await shot('variables')
    actions.push('variable timeline and line locator')
    await chooseTab('知识检索')
    await page.getByRole('searchbox', { name: '知识库查询' }).fill('calculate')
    await page.getByRole('radio', { name: '关键词检索' }).check()
    await page.getByRole('button', { name: '检索代码证据', exact: true }).click()
    await page.locator('.results-heading').waitFor()
    await shot('search')
    actions.push('keyword search accepted by API')
    await chooseTab('详细说明书')
    await page.getByRole('button', { name: '生成本地完整说明', exact: false }).click()
    await page.getByText('完整说明书已生成。所有说明都应结合右侧对应版本的源码核对。', { exact: true }).waitFor({ timeout: 30000 })
    await page.locator('.markdown-body').waitFor({ timeout: 30000 })
    assert.ok((await page.locator('.markdown-body').innerText()).length > 5000)
    await page.getByText('后台已自动保存 Markdown 文档。', { exact: false }).waitFor()
    const downloadPromise = page.waitForEvent('download')
    await page.getByRole('link', { name: '下载完整 Markdown', exact: false }).click()
    const download = await downloadPromise
    await download.saveAs(path.join(output, 'v02-ui-downloaded-manual.md'))
    assert.ok(fs.statSync(path.join(output, 'v02-ui-downloaded-manual.md')).size > 5000)
    await shot('manual')
    actions.push('offline manual generation, >5000 automatic document, actual download')
    await page.getByRole('button', { name: 'DeepSeek 深入讲解 · 先预览', exact: true }).click()
    const previewDialog = page.getByRole('dialog', { name: '确认本次发送范围' })
    await previewDialog.waitFor()
    assert.ok((await previewDialog.locator('.preview-context').innerText()).length > 100)
    await shot('ai-preview-only')
    await previewDialog.getByRole('button', { name: '返回调整', exact: true }).click()
    actions.push('real AI context and cost preview only; cancelled without paid request')
    await page.getByRole('button', { name: '导入新版本', exact: true }).click()
    await page.getByRole('button', { name: '粘贴源码', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: '导入 Python 项目' })
    await dialog.getByLabel('项目名称', { exact: true }).fill('浏览器联调版本项目')
    await dialog.getByLabel('文件名', { exact: true }).fill('main.py')
    await dialog.getByLabel('Python 源码', { exact: true }).fill('def calculate(value):\n    result = value + 1\n    return result\n\nif __name__ == "__main__":\n    print(calculate(2))\n')
    await dialog.getByRole('button', { name: '导入并建立阅读地图', exact: false }).click()
    await page.getByRole('heading', { name: '浏览器联调版本项目 Python' }).waitFor({ timeout: 30000 })
    await page.getByRole('button', { name: '导入新版本', exact: true }).click()
    await dialog.getByRole('button', { name: '粘贴源码', exact: true }).click()
    await dialog.getByLabel('Python 源码', { exact: true }).fill('def calculate(value):\n    result = value + 2\n    return result\n\nif __name__ == "__main__":\n    print(calculate(2))\n')
    await dialog.getByRole('button', { name: '导入并建立阅读地图', exact: false }).click()
    await dialog.waitFor({ state: 'hidden', timeout: 30000 })
    await chooseTab('版本对比')
    await page.getByRole('button', { name: '查看代码变化', exact: true }).click()
    await page.locator('.diff-card').waitFor()
    assert.ok((await page.locator('.diff-code').innerText()).includes('value + 2'))
    await shot('diff')
    actions.push('paste import two revisions and real version diff')
    await page.getByRole('button', { name: '导入新版本', exact: true }).click()
    await dialog.getByRole('button', { name: '选择文件 / 文件夹', exact: true }).click()
    await dialog.getByLabel('项目名称', { exact: true }).fill('空包文件上传测试')
    await dialog.locator('input[type=file][accept=".py"]').setInputFiles([
      { name: '__init__.py', mimeType: 'text/x-python', buffer: Buffer.from('') },
      { name: 'logic.py', mimeType: 'text/x-python', buffer: Buffer.from('def add(a, b):\n    return a + b\n') },
    ])
    await dialog.getByText('已选择 2 个 Python 文件', { exact: true }).waitFor()
    await dialog.getByRole('button', { name: '导入并建立阅读地图', exact: false }).click()
    await dialog.waitFor({ state: 'hidden', timeout: 30000 })
    await page.getByRole('heading', { name: '空包文件上传测试 Python' }).waitFor()
    assert.equal(await page.locator('.module-card').count(), 2)
    actions.push('multiple-file upload accepts an empty first __init__.py')
    await page.getByRole('button', { name: '模型与设置', exact: false }).click()
    await page.getByRole('button', { name: '保存密钥', exact: true }).click()
    await page.getByText('请填写 API Key。', { exact: true }).waitFor()
    assert.equal(await page.locator('input[type=password]').inputValue(), '')
    await shot('settings')
    actions.push('settings empty-key validation; no API key changed or paid AI sent')
    await page.route('**/api/jobs/*', route => route.fulfill({ contentType: 'application/json', body: JSON.stringify({ id: 'interrupted-browser-fixture', status: 'interrupted', progress: 5, error: '测试模拟：后台重启后任务已中断，请重新操作。' }) }))
    await page.getByRole('button', { name: '打开示例项目', exact: false }).click()
    await page.getByText('测试模拟：后台重启后任务已中断，请重新操作。', { exact: true }).waitFor({ timeout: 5000 })
    await page.locator('.sidebar-action:has-text("打开示例项目"):not(:disabled)').waitFor({ timeout: 1000 })
    assert.equal(await page.locator('.task-progress').count(), 0)
    await page.unroute('**/api/jobs/*')
    actions.push('explicitly mocked interrupted job exits polling and restores controls immediately')
    assert.deepEqual(errors, [])
    assert.deepEqual(failures, [])
    assert.equal(paidRequests, 0)
    fs.writeFileSync(path.join(output, 'v02-ui-browser-results.json'), JSON.stringify({ ok: true, base, checked_at: new Date().toISOString(), actions, errors, failed_responses: failures, paid_requests: paidRequests }, null, 2))
    console.log(JSON.stringify({ ok: true, actions, errors, failed_responses: failures, paid_requests: paidRequests }, null, 2))
  } catch (error) {
    await shot('failure')
    fs.writeFileSync(path.join(output, 'v02-ui-browser-results.json'), JSON.stringify({ ok: false, actions, errors, failed_responses: failures, paid_requests: paidRequests, failure: error.stack }, null, 2))
    throw error
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
